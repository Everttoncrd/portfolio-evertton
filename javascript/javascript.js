/* ========================================
   OBSERVADOR DAS ANIMAÇÕES
======================================== */

const revealObserver =
    new IntersectionObserver(

        function (
            entries,
            observer
        ) {

            entries.forEach(
                function (entry) {

                    if (
                        entry.isIntersecting
                    ) {

                        entry.target
                            .classList
                            .add("active");


                        observer.unobserve(
                            entry.target
                        );

                    }

                }
            );

        },

        {
            threshold: 0.12,

            rootMargin:
                "0px 0px -40px 0px"
        }

    );


document
    .querySelectorAll(
        ".reveal, " +
        ".reveal-left, " +
        ".reveal-right"
    )
    .forEach(
        function (element) {

            revealObserver.observe(
                element
            );

        }
    );


