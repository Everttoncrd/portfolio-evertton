const typingElement =
    document.querySelector(".typing-text");


const typingTextsByLanguage = {
    pt: [
        "Desenvolvedor",
        "Desenvolvedor Front-end",
        "Desenvolvedor Back-end",
        "Python | JavaScript | React"
    ],
    en: [
        "Developer",
        "Front-end Developer",
        "Back-end Developer",
        "Python | JavaScript | React"
    ]
};

let currentLanguage = localStorage.getItem("portfolioLanguage") || "pt";
let typingTexts = typingTextsByLanguage[currentLanguage];


let textIndex = 0;
let characterIndex = 0;
let isDeleting = false;


function typingEffect() {

    if (!typingElement) {
        return;
    }


    const currentText =
        typingTexts[textIndex];


    if (!isDeleting) {

        typingElement.textContent =
            currentText.substring(
                0,
                characterIndex + 1
            );

        characterIndex++;


        if (
            characterIndex ===
            currentText.length
        ) {

            isDeleting = true;

            setTimeout(
                typingEffect,
                1500
            );

            return;

        }

    } else {

        typingElement.textContent =
            currentText.substring(
                0,
                characterIndex - 1
            );

        characterIndex--;


        if (characterIndex === 0) {

            isDeleting = false;

            textIndex++;


            if (
                textIndex ===
                typingTexts.length
            ) {

                textIndex = 0;

            }

        }

    }


    const typingSpeed =
        isDeleting ? 45 : 90;


    setTimeout(
        typingEffect,
        typingSpeed
    );

}


setLanguage(currentLanguage);

if (typingElement) {

    typingEffect();

}


